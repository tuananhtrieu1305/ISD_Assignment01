// Current built UI + real KG fixture, intercepted local API; zero model calls.
import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {layoutGraph} from '../../web/frontend/src/kg-layout.js';
const root=path.resolve(import.meta.dirname,'../../..'),P=path.join(root,'project01');
const out=path.join(P,'artifacts/llm_v2/phase2/development/four_agent_r11');
const graph=JSON.parse(await fs.readFile(path.join(out,'graph_fixture.json'),'utf8'));
const fixture=JSON.parse(await fs.readFile(path.join(out,'offline_pipeline_fixture.json'),'utf8'));
const checks=[],errors=[],requests=[];let submitted=null;
const ok=(value,name)=>{assert(value,name);checks.push(name);};
const positions=layoutGraph(graph.nodes,graph.edges);
ok(Object.keys(positions).length===graph.nodes.length&&Object.values(positions).every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)),'local layout has finite positions for all real KG nodes');
ok(JSON.stringify(positions)===JSON.stringify(layoutGraph(graph.nodes,graph.edges)),'graph layout is deterministic without an external service');
const browser=await chromium.launch({headless:true,executablePath:path.join(root,'.local/ms-playwright/chromium-1248/chrome-win64/chrome.exe')});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.route('**/*',async route=>{
  const url=new URL(route.request().url());if(url.hostname!=='offline-r11.local')return route.abort();
  requests.push(url.pathname);
  if(url.pathname==='/ready')return route.fulfill({json:{status:'ready',live_enabled:true,runtime_revision:'four-agent-r11',generation_model:'gemini-3-flash-preview',usage:{generation_cap:18,generation_attempts:0}}});
  if(url.pathname==='/api/v2/compare'){submitted=route.request().postDataJSON();return route.fulfill({json:{id:'offline-r11'}});}
  if(url.pathname==='/api/v2/jobs/offline-r11')return route.fulfill({json:{...fixture,elapsed_seconds:0}});
  if(url.pathname==='/api/v2/knowledge-graph')return route.fulfill({json:graph});
  if(url.pathname.startsWith('/api/'))return route.abort();
  return route.fulfill({path:path.join(P,'web/frontend/dist',url.pathname==='/'?'index.html':url.pathname.slice(1))});
 });
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://offline-r11.local',{waitUntil:'networkidle'});
 ok(await page.locator('main textarea').count()===1&&await page.locator('main form input,main form select').count()===0,'question screen has one input and no profile fields');
 ok(await page.locator('main form button').count()===1,'question form has only the answer button');
 ok(await page.getByRole('button',{name:/So sánh & đánh giá/}).count()===0,'evaluation tab removed');
 await page.screenshot({path:path.join(out,'question-only-desktop.png'),fullPage:true});
 await page.getByRole('textbox',{name:'Câu hỏi của bạn'}).fill(fixture.question);
 await page.getByRole('button',{name:/^Trả lời/}).click();
 await page.getByText(/OFFLINE FIXTURE: câu trả lời minh họa/).first().waitFor();
 ok(JSON.stringify(Object.keys(submitted))==='["question"]','job payload contains only the user question');
 await page.getByRole('button',{name:/03.*Luồng xử lý/}).click();
 ok(await page.locator('.pipeline-map').count()===1&&await page.locator('.agent-role-map').count()===0,'only one pipeline diagram remains');
 ok(await page.locator('.pipeline-map a').count()===4&&await page.locator('.pipeline-stage').count()===4,'diagram and detailed sections both have four matching agents');
 ok(await page.locator('.agent-substep').count()===6,'retrieval/rerank and release are grouped inside four roles');
 ok(!await page.locator('main').textContent().then(t=>t.includes('Risk Agent')),'current flow contains no Risk agent');
 await page.screenshot({path:path.join(out,'single-four-agent-pipeline.png'),fullPage:true});
 await page.locator('.pipeline-map').screenshot({path:path.join(out,'four-agent-overview.png')});
 await page.getByRole('button',{name:/04.*Đồ thị tri thức/}).click();
 await page.locator('[data-node-id]').first().waitFor();
 ok(await page.locator('[data-node-id]').count()===35&&await page.locator('[data-edge-id]').count()===35,'graph renders the actual35nodes and35edges');
 await page.screenshot({path:path.join(out,'knowledge-graph-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Phóng to đồ thị',exact:true}).click();
 ok(await page.locator('.kg-controls').textContent().then(t=>t.includes('120%')),'graph zoom control works');
 await page.getByRole('button',{name:'Đặt lại',exact:true}).click();
 const node=page.locator('[data-node-id="diabetes"]'),before=await node.getAttribute('transform'),box=await node.locator('circle').boundingBox();
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2+35,box.y+box.height/2+20,{steps:6});await page.mouse.up();
 ok(await node.getAttribute('transform')!==before,'nodes can be dragged locally');
 await page.getByRole('button',{name:'Đặt lại',exact:true}).click();
 const edge=page.locator('[data-edge-id]').first();await edge.focus();await page.keyboard.press('Enter');
 ok(await page.locator('.kg-inspector blockquote').textContent()===graph.edges[0].quote,'selecting an edge exposes its exact source quote');
 ok(await page.locator('.kg-inspector a').getAttribute('href')===graph.edges[0].source_url,'edge source URL is not invented');
 await page.locator('#kg-search').fill('thận');
 ok(await page.locator('.kg-search-results button').count()>0,'Vietnamese entity search works');
 await page.locator('.kg-search-results button').first().click();
 ok(await page.locator('.kg-related button').count()>0,'node selection exposes neighboring relations');
 await page.screenshot({path:path.join(out,'knowledge-graph-source-inspector.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'graph is usable without page overflow on mobile');
 await page.screenshot({path:path.join(out,'knowledge-graph-mobile.png'),fullPage:true});
 ok(!requests.some(p=>/examples|summary|risk|development/.test(p)),'simplified UI never fetches profiles or evaluation');
 ok(errors.length===0,'no browser JavaScript errors');
 const receipt={status:'PASS',checks,errors,requests,new_generation_API_calls:0,new_embedding_API_calls:0,fixture:'engineering-only generation mock, real source KG'};
 await fs.writeFile(path.join(out,'ui_verification.json'),JSON.stringify(receipt,null,2));console.log(JSON.stringify(receipt));
}finally{await browser.close();}
