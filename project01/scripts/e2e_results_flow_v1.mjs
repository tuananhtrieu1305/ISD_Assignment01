  await run();
  const summary=page.getByRole('region',{name:'So sánh cách xử lý'});
  assert(await summary.getByRole('heading',{name:'P2 · Điều phối, kiểm chứng và tổng hợp',exact:true}).isVisible(),'P2 processing heading');
